using 游戏服务器.数据类;
using 游戏服务器.模板类;

namespace 游戏服务器.管理命令;

// 借鉴移植(参考引擎): 发放/删除/续期限时称号。适配: 参照 玩家称号到期/玩家获得称号 带 caller/line 尾参, 我方签名为 (byte)/(byte,int) 去尾参。
public sealed class 开关称号 : GM命令
{
	[字段描述(0, 排序 = 0)]
	public string 角色名字;

	[字段描述(0, 排序 = 1)]
	public byte 称号编号;

	[字段描述(0, 排序 = 2)]
	public int 有效小时;

	[字段描述(0, 排序 = 3, 可选 = true)]
	public bool 删除称号;

	public override 执行方式 执行方式 => 执行方式.优先后台执行;

	public override void 执行命令()
	{
		if (!游戏称号.数据表.TryGetValue(称号编号, out var 称号))
		{
			主程.添加命令日志($"<= @{GetType().Name} 命令执行失败, 称号编号: {称号编号} 不存在");
		}
		else if (游戏数据网关.角色数据表.检索表.TryGetValue(角色名字, out var value) && value is 角色数据 角色数据)
		{
			if (删除称号)
			{
				if (!角色数据.称号列表.ContainsKey(称号编号))
				{
					主程.添加命令日志("<= @" + GetType().Name + " 命令执行失败, 玩家未佩戴: " + 称号.称号名字);
					return;
				}
				if (角色数据.网络连接?.绑定角色 == null)
				{
					角色数据.称号列表.Remove(称号编号);
					return;
				}
				角色数据.网络连接.绑定角色.玩家称号到期(称号编号);
			}
			else
			{
				if (角色数据.称号列表.ContainsKey(称号编号))
				{
					角色数据.称号列表[称号编号] = 主程.当前时间.AddMinutes(有效小时);
					主程.添加命令日志($"<= @{GetType().Name} 命令执行成功, 玩家已拥有: {称号.称号名字},到期时间修改为:{角色数据.称号列表[称号编号]}");
					return;
				}
				if (角色数据.网络连接?.绑定角色 == null)
				{
					角色数据.称号列表.Add(称号编号, 主程.当前时间.AddMinutes(有效小时));
					return;
				}
				角色数据.网络连接.绑定角色.玩家获得称号(称号编号, 有效小时);
			}
			主程.添加命令日志($"<= @{GetType().Name} 命令已经执行,  {称号.称号名字},到期时间:{角色数据.称号列表[称号编号]}");
			主程.添加系统日志($"[@开关称号]{角色名字} 获得称号 {称号.称号名字},到期时间:{角色数据.称号列表[称号编号]}", true, true);
		}
		else
		{
			主程.添加命令日志("<= @" + GetType().Name + " 命令执行失败, 角色不存在");
		}
	}
}
