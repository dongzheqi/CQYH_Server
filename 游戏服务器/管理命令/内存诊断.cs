using System;
using System.Collections.Generic;
using System.Diagnostics;
using 游戏服务器.地图类;
using 游戏服务器.工具类;
using 游戏服务器.性能优化;
using 游戏服务器.网络类;

namespace 游戏服务器.管理命令;

public class 内存诊断 : GM命令
{
	[字段描述(0, 可选 = true)]
	public string 参数;

	public override 执行方式 执行方式 => 执行方式.只能后台执行;

	public override void 执行命令()
	{
		try
		{
			switch (参数?.ToLower())
			{
			case "状态":
			case "status":
				显示自动清理状态();
				break;
			case "启用详细":
			case "verbose":
				性能优化配置.启用详细内存日志 = true;
				性能优化配置.保存配置文件();
				主程.添加命令日志("<= 详细内存日志已启用");
				break;
			case "禁用详细":
			case "noverbose":
				性能优化配置.启用详细内存日志 = false;
				性能优化配置.保存配置文件();
				主程.添加命令日志("<= 详细内存日志已禁用");
				break;
			default:
				完整诊断();
				break;
			}
		}
		catch (Exception ex)
		{
			主程.添加命令日志("<= @内存诊断 执行失败: " + ex.Message);
		}
	}

	private void 完整诊断()
	{
		主程.添加命令日志("<= @内存诊断 开始收集信息...");
		主程.添加命令日志("【GC内存信息】");
		string[] array = 内存监控器.获取内存诊断报告().Split('\n');
		foreach (string text in array)
		{
			if (!string.IsNullOrWhiteSpace(text))
			{
				主程.添加命令日志("  " + text);
			}
		}
		主程.添加命令日志("【核心对象统计】");
		主程.添加命令日志($"  玩家对象表: {地图处理网关.玩家对象表?.Count ?? 0}");
		主程.添加命令日志($"  怪物对象表: {地图处理网关.怪物对象表?.Count ?? 0}");
		主程.添加命令日志($"  宠物对象表: {地图处理网关.宠物对象表?.Count ?? 0}");
		主程.添加命令日志($"  物品对象表: {地图处理网关.物品对象表?.Count ?? 0}");
		主程.添加命令日志($"  守卫对象表: {地图处理网关.守卫对象表?.Count ?? 0}");
		主程.添加命令日志($"  地图实例表: {地图处理网关.地图实例表?.Count ?? 0}");
		int num = 地图处理网关.副本实例表?.Count ?? 0;
		int num2 = 0;
		long num3 = 0L;
		long num4 = 0L;
		if (地图处理网关.副本实例表 != null)
		{
			foreach (地图实例 item in 地图处理网关.副本实例表)
			{
				if (item.副本关闭)
				{
					num2++;
				}
				if (item.获取怪物列表() != null)
				{
					num3 += item.获取怪物列表().Count;
				}
				List<守卫实例> list = item.获取守卫列表();
				if (list != null)
				{
					num4 += list.Count;
				}
			}
		}
		主程.添加命令日志($"  副本实例表: {num} (已关闭: {num2})");
		if (num > 50)
		{
			主程.添加命令日志($"  ⚠ 警告: 副本实例数量过多({num})，可能存在副本泄漏");
		}
		主程.添加命令日志("【网络连接统计】");
		主程.添加命令日志($"  网络连接表: {网络服务网关.网络连接表?.Count ?? 0}");
		主程.添加命令日志($"  门票数据表: {网络服务网关.门票数据表?.Count ?? 0}");
		主程.添加命令日志($"  全服公告表: {网络服务网关.全服公告表?.Count ?? 0}");
		long num5 = 0L;
		long num6 = 0L;
		long num7 = 0L;
		foreach (地图实例 value2 in 地图处理网关.地图实例表.Values)
		{
			if (value2?.获取怪物列表() != null)
			{
				num5 += value2.获取怪物列表().Count;
			}
			if (value2?.物品列表 != null)
			{
				num6 += value2.物品列表.Count;
			}
			List<守卫实例> list2 = value2?.获取守卫列表();
			if (list2 != null)
			{
				num7 += list2.Count;
			}
		}
		主程.添加命令日志("【地图分布统计】");
		主程.添加命令日志($"  地图怪物总数: {num5}");
		主程.添加命令日志($"  地图物品总数: {num6}");
		主程.添加命令日志($"  地图守卫总数: {num7}");
		主程.添加命令日志("【副本分布统计】");
		主程.添加命令日志($"  副本怪物总数: {num3}");
		主程.添加命令日志($"  副本守卫总数: {num4}");
		主程.添加命令日志($"  平均每副本怪物: {((num > 0) ? (num3 / num) : 0)}");
		long num8 = 0L;
		long num9 = 0L;
		string value = "";
		foreach (玩家实例 value3 in 地图处理网关.玩家对象表.Values)
		{
			if (value3?.技能任务 != null)
			{
				int count = value3.技能任务.Count;
				num8 += count;
				if (count > num9)
				{
					num9 = count;
					value = value3.对象名字;
				}
			}
		}
		主程.添加命令日志("【技能实例统计】");
		主程.添加命令日志($"  总技能任务数: {num8}");
		主程.添加命令日志($"  平均每玩家: {((地图处理网关.玩家对象表.Count > 0) ? (num8 / 地图处理网关.玩家对象表.Count) : 0)}");
		if (num9 > 10)
		{
			主程.添加命令日志($"  ⚠ 注意: [{value}] 有 {num9} 个技能任务，可能异常");
		}
		主程.添加命令日志("【性能优化配置】");
		主程.添加命令日志("  " + 性能优化配置.获取配置摘要());
		主程.添加命令日志("<= @内存诊断 完成");
	}

	private void 显示自动清理状态()
	{
		主程.添加命令日志("<= @内存诊断 [自动清理状态]");
		主程.添加命令日志($"  高性能模式: {性能优化配置.高性能模式}");
		主程.添加命令日志($"  启用自动清理: {性能优化配置.启用自动清理内存}");
		主程.添加命令日志($"  详细内存日志: {性能优化配置.启用详细内存日志}");
		主程.添加命令日志($"  内存监控间隔: {性能优化配置.内存监控间隔} 分钟");
		主程.添加命令日志($"  自动清理间隔: {性能优化配置.自动清理内存间隔} 分钟");
		主程.添加命令日志($"  内存阈值: {性能优化配置.内存阈值MB} MB");
		double num = (double)Process.GetCurrentProcess().PrivateMemorySize64 / 1024.0 / 1024.0;
		主程.添加命令日志($"  当前内存使用: {num:F2} MB");
		if (num > (double)性能优化配置.内存阈值MB)
		{
			主程.添加命令日志("  状态: ⚠ 内存超过阈值，应该触发自动清理");
		}
		else
		{
			主程.添加命令日志($"  状态: ✓ 内存正常，距阈值还有 {(double)性能优化配置.内存阈值MB - num:F2} MB");
		}
		主程.添加命令日志("<= 建议:");
		主程.添加命令日志("  如果发现自动清理不工作:");
		主程.添加命令日志("  1. 使用 '@内存诊断 启用详细' 查看详细日志");
		主程.添加命令日志("  2. 修改 配置/性能优化配置.json 后重启生效(阈值/间隔/开关)");
		主程.添加命令日志("  3. 使用 '@清理内存' 手动触发清理");
		主程.添加命令日志("  注: 超阈值时的强制清理最快 60 秒一次, 连续清理无效会退避到最长 8 分钟");
	}
}
